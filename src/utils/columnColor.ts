/**
 * 2단 행의 칸마다 붙는 **고유 색** — 모바일 배치를 고를 때 "어느 칸"인지 위치(왼쪽/오른쪽)가 아니라
 * 색으로 알아보게 한다.
 *
 * 위치로 부르면 캔버스에서 좌우 자리를 바꾸는 순간 '왼쪽 칸'이 다른 내용을 가리켜 헷갈렸다.
 * 색은 **내용을 따라간다**: 처음에는 왼쪽 칸이 A(파랑), 오른쪽 칸이 B(주황)이고, 좌우 자리 바꾸기를 할 때마다
 * 그 행의 '바뀜' 표시(group.swappedRows)가 뒤집혀 색도 내용과 함께 옮겨 간다.
 * 캔버스(칸 위 점·모듈 툴바 위 점)와 행 패널의 모바일 배치 카드가 같은 색을 쓴다.
 *
 * ⚠ 모듈 id 순서로 정하면 안 된다 — 조립형 모듈은 같은 밀리초에 만들어져 id의 시각이 같고,
 *   뒤의 난수에 따라 처음부터 왼쪽이 주황이 되기도 했다.
 */
/** name 은 점 안에 적고 카드 이름에도 쓰는 칸 이름 — 색만으로 부르면 색을 말로 옮기기 어렵다('A 칸 위') */
export const COLUMN_COLORS = [
  { css: 'var(--blue-400)', name: 'A' },
  { css: 'var(--yellow-400)', name: 'B' },
] as const

/** 칸별 번호(0=A 파랑, 1=B 주황). 좌우를 바꾼 행이면 뒤집는다 */
export const columnColorSlots = (swapped: boolean | undefined): [number, number] => (swapped ? [1, 0] : [0, 1])
